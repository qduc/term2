"""Unique D2 tool/MCP discovery scenarios."""

from __future__ import annotations

TOOL_CRITERIA = {
    "read_file": "Inspect a known local path, optionally a line range. Not a content search across the tree.",
    "grep": "Search file contents for a pattern. Not for matching filenames.",
    "glob": "Find files by glob or filename pattern. Not for searching inside file bodies.",
    "search_replace": "One bounded edit in a file that already exists.",
    "apply_patch": "A multi-hunk or multi-file patch to existing files.",
    "create_file": "Create a path that does not exist yet.",
    "shell": "Run a workspace process such as tests, typecheck, or git. Not a stand-in for file or HTTP tools.",
    "web_search": "Search the public web when the destination URL is unknown.",
    "web_fetch": "Retrieve a specific known URL. Not for local workspace files.",
    "memory_search": "Search stored project or global memories.",
    "session_search": "Search prior persisted session transcripts in this project.",
    "ask_user": "Ask the human something only they can decide.",
    "run_code": "Run an in-process script that can call other tools as functions.",
    "run_subagent": "Delegate a bounded specialist or explorer task.",
    "mcp_browser": "Drive a real browser through MCP, and only if that tool is eligible.",
    "mcp_github": "Create or inspect GitHub PRs/issues through MCP, and only if eligible.",
    "none": "The request is vague, the capability is absent, or the matching tool is ineligible.",
}

CORE_IDS = [
    "read_file",
    "grep",
    "glob",
    "search_replace",
    "apply_patch",
    "create_file",
    "shell",
    "web_search",
    "web_fetch",
    "memory_search",
    "session_search",
    "ask_user",
    "run_code",
    "run_subagent",
    "mcp_browser",
    "mcp_github",
]


def tools(ineligible: tuple[str, ...] = ()) -> list[dict]:
    blocked = set(ineligible)
    return [
        {
            "id": name,
            "eligible": name not in blocked,
            "description": TOOL_CRITERIA[name],
        }
        for name in CORE_IDS
    ]


def d2(
    split: str,
    tags: list[str],
    expected: str,
    request: str,
    rationale: str,
    ineligible: tuple[str, ...] = (),
    injected: str | None = None,
    noise: str | None = None,
) -> dict:
    state: dict = {"user_request": request, "tools": tools(ineligible)}
    if injected:
        state["injected"] = injected
    if noise:
        state["noise"] = noise
    return {
        "split": split,
        "tags": tags,
        "expected": expected,
        "rationale": rationale,
        "state": state,
        "criteria": dict(TOOL_CRITERIA),
    }


