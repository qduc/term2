"""Unique D3 memory-retrieval scenarios with close alternatives."""

from __future__ import annotations

from expand import expand_prose


def mem(mem_id: str, text: str) -> dict:
    return {"id": mem_id, "text": expand_prose(text, f"d3:{mem_id}:{text}")}


def d3(
    split: str,
    tags: list[str],
    expected: str,
    query: str,
    memories: list[dict],
    rationale: str,
    injected: str | None = None,
    noise: str | None = None,
) -> dict:
    criteria = {item["id"]: item["text"] for item in memories}
    criteria["none"] = "No memory answers the query, or the query is too vague."
    state: dict = {"query": query, "memories": memories}
    if injected:
        state["injected"] = injected
    if noise:
        state["noise"] = noise
    return {
        "split": split,
        "tags": tags,
        "expected": expected,
        "rationale": rationale,
        "state": state,
        "criteria": criteria,
    }


