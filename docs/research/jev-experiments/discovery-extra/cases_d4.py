"""Unique D4 prior-session retrieval scenarios."""

from __future__ import annotations

from expand import expand_prose


def sess(sid: str, provenance: str, text: str) -> dict:
    return {"id": sid, "provenance": provenance, "text": expand_prose(text, f"d4:{sid}:{text}")}


def d4(
    split: str,
    tags: list[str],
    expected: str,
    query: str,
    sessions: list[dict],
    rationale: str,
    noise: str | None = None,
) -> dict:
    criteria = {item["id"]: item["text"] for item in sessions}
    criteria["none"] = "No excerpt matches the queried decision or task, or the query is empty."
    state: dict = {"query": query, "sessions": sessions}
    if noise:
        state["noise"] = noise
    return {
        "split": split,
        "tags": tags,
        "expected": expected,
        "rationale": rationale,
        "state": state,
        "criteria": criteria,
    }


