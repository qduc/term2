"""Unique D5 code/search passage scenarios."""

from __future__ import annotations

from expand import expand_code


def pas(pid: str, path: str, text: str) -> dict:
    return {"id": pid, "path": path, "text": expand_code(path, text, f"d5:{pid}:{path}:{text}")}


def d5(
    split: str,
    tags: list[str],
    expected: str,
    query: str,
    passages: list[dict],
    rationale: str,
    noise: str | None = None,
) -> dict:
    criteria = {item["id"]: f"{item['path']}: {item['text']}" for item in passages}
    criteria["none"] = "The queried symbol or behavior is not in any passage."
    state: dict = {"query": query, "passages": passages}
    if noise:
        state["noise"] = noise
    return {
        "split": split,
        "tags": tags,
        "expected": expected,
        "rationale": rationale,
        "state": state,
        "criteria": criteria,
    }


