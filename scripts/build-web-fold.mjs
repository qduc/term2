#!/usr/bin/env node
// Builds the web client's copy of the shared fold (src/protocol/fold/) into web-client/lib/term2/generated/:
//   wire-fold.js     one ESM file bundled from src/protocol/fold-browser.ts (the fold plus term2's tool labels)
//   wire-fold.d.ts   its types, re-exporting the declarations emitted for src/protocol/fold/ into fold/
// The browser runs the same code as the server and the TUI, so it holds no reducer of its own. The output is
// not committed; scripts/build-web.mjs and the CI web typecheck step run this first. Direct source imports
// are not used because Turbopack did not resolve the fold's `.js` specifiers (web-client/WIRE.md).
import { execFileSync } from 'node:child_process';
import { mkdirSync, rmSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';

const root = fileURLToPath(new URL('../', import.meta.url));
const out = path.join(root, 'web-client/lib/term2/generated');

rmSync(out, { recursive: true, force: true });
mkdirSync(out, { recursive: true });

await build({
  entryPoints: [path.join(root, 'src/protocol/fold-browser.ts')],
  outfile: path.join(out, 'wire-fold.js'),
  bundle: true,
  format: 'esm',
  platform: 'browser',
  target: 'es2020',
  legalComments: 'none',
  logLevel: 'warning',
});

// The fold imports nothing outside its folder (the fold-boundary rule), so this emits the fold's files only.
execFileSync(
  process.execPath,
  [
    createRequire(import.meta.url).resolve('typescript/lib/tsc.js'),
    '--ignoreConfig',
    '--declaration',
    '--emitDeclarationOnly',
    '--strict',
    '--skipLibCheck',
    '--target',
    'es2022',
    '--module',
    'nodenext',
    '--moduleResolution',
    'nodenext',
    '--rootDir',
    path.join(root, 'src/protocol/fold'),
    '--outDir',
    path.join(out, 'fold'),
    path.join(root, 'src/protocol/fold/index.ts'),
  ],
  { stdio: 'inherit' },
);

writeFileSync(
  path.join(out, 'wire-fold.d.ts'),
  `// Generated by scripts/build-web-fold.mjs; do not edit.
import type { WireEvent, WireSnapshot } from './fold/index.js';
export type * from './fold/index.js';
/** The shared fold, with the same options the server uses. */
export declare function reduceWireEvent(state: WireSnapshot, event: WireEvent): WireSnapshot;
/** Whether a provider is billed via a subscription plan rather than metered per-token spend. */
export declare function isSubscriptionProvider(provider: string | undefined): boolean;
`,
);
